"""Write RESULTS.md from computed numbers only. No paper text, tables or figures are reused."""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from . import data as D


def _f(x, k=2):
    return f"{x:.{k}f}"


def _p(p):
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def _table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("-" for _ in cols) + "|"]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def write_results_md(path: Path, s: dict, *, audit, groups, demo, adj, unadj, adj_clean, flags,
                     shared, shrink, cls, age_eff) -> None:
    ctr = s["contrasts"]
    imp = s["imputation"]
    fis = imp["fisher_controls_vs_patients"]
    lc = s["leakage_classification"]
    dm = s["demographics"]
    au = s["audit"]

    def auc(name):
        v = lc[name]
        return f"{v['auc_mean']:.3f} ({v['auc_p2_5_p97_5'][0]:.3f} to {v['auc_p2_5_p97_5'][1]:.3f})"

    keys = list(lc.keys())
    out = []
    w = out.append
    w("# GaitClass Lab: results")
    w("")
    w("**Status: public.** The analysis repository is public at "
      "https://github.com/victorgomezadapty/gaitclass-lab. Generated by `scripts/run_analysis.py` from the local copy of the "
      "deposited workbook. Every number below is computed in this project; nothing is copied from the companion paper.")
    w("")
    w("This is a transparent re-analysis of an open table of participant level gait means. It is not a new "
      "clinical study and not a replication of the paper's machine learning classifier. Each section says "
      "what comes from the deposit, what is inferred, and what this analysis adds.")
    w("")
    w("## 1. Source and provenance")
    w("")
    w(f"* Deposit title: *{D.DATASET_TITLE}*. \"GaitClass\" is only the file and project short name.")
    w(f"* Zenodo record {D.ZENODO_RECORD}, version DOI {D.ZENODO_DOI}, concept DOI {D.ZENODO_CONCEPT_DOI}, "
      "license id `cc-by-4.0`, open access, one file.")
    w(f"* File `{D.RAW_NAME}`, {D.EXPECTED_BYTES} bytes, md5 `{D.EXPECTED_MD5}` (verified before every load).")
    w(f"* Sheet `Dataset`: {s['n_participants']} rows, {s['n_columns']} columns (one fully empty trailing column "
      f"dropped). Missing cells in the file: {s['missing_cells_in_file']} (gaps were already imputed by the depositors). "
      "Sheet `Parameter definition`: a 28 row codebook.")
    w("* Direct identifiers: none (no names, dates, contact data, record numbers or images of people). "
      "ID is a sequential study number 1 to 206. Quasi identifiers: age in years, sex, BMI, diagnosis group.")
    w(f"* Ethics as reported in the companion paper: Ethics Committee Northwest Switzerland, {D.ETHICS}; "
      "signed informed consent; retrospective pooling of earlier projects. No trial registration was found.")
    w(f"* Companion paper (cited only, CC BY-NC-ND 4.0): Dammeyer C, et al. J Orthop Res 2024;42(7):1463 to 1472. "
      f"https://doi.org/{D.PAPER_DOI}, PMID {D.PAPER_PMID}.")
    w("")
    w("## 2. Group codes (inferred mapping)")
    w("")
    w(f"The codebook says: \"{D.CODEBOOK_GROUP_TEXT}\". Code 1 appears twice and code 0 is never listed, "
      "while the file uses codes 0 to 4.")
    w("")
    g = groups[["code", "observed_n", "label_used", "reported_n_zenodo_and_paper", "counts_match"]].copy()
    g.columns = ["code", "n in file", "label used here", "n reported (Zenodo, paper)", "match"]
    w(_table(g))
    w("")
    w("**Inferred, not stated:** code 0 = healthy control is inferred because its count (96) equals the number of "
      "controls reported on Zenodo and in the paper. Codes 1 to 4 follow the codebook and their counts also match. "
      "The codebook itself never says 0 = healthy. See `tables/t03_group_codes_inferred_mapping.csv` and "
      "`figures/fig01_group_codes.png`.")
    w("")
    w("## 3. Data quality audit")
    w("")
    w(f"{au['n_flagged_columns']} columns carry a flag. {au['codebook_name_mismatches']} raw headers do not match their "
      f"codebook names and {au['headers_with_whitespace']} headers carry leading or trailing spaces. "
      "Nothing was silently fixed; full table in `tables/t02_data_quality_audit.csv`, figure "
      "`figures/fig02_data_quality_audit.png`.")
    w("")
    a = audit[audit["flag"] != ""][["column", "codebook_unit", "min", "max", "flag"]].copy()
    a["min"] = a["min"].map(lambda x: _f(x)); a["max"] = a["max"].map(lambda x: _f(x))
    w(_table(a))
    w("")
    w(f"* **Stance**: unit says seconds, values run {au['stance_range'][0]} to {au['stance_range'][1]}. "
      "Assumption used in this project: percent of the gait cycle. The column is renamed `StancePct`; values unchanged.")
    w(f"* **KneeMinimum**: {au['knee_minimum_range'][0]} to {au['knee_minimum_range'][1]}, against KneeMaximum "
      f"{au['knee_maximum_range'][0]} to {au['knee_maximum_range'][1]} degrees. Scale unknown, so KneeMinimum and "
      "its side difference are excluded from contrasts and classifiers and shown only descriptively.")
    w(f"* **HipMinimum**: described as \"Global hip maximum\", yet the largest value is {au['hip_minimum_max_value']} "
      "(all negative). Treated as a minimum, as the column name says.")
    w("* **Speed**: description reads \"Meters\"; values fit m/s. **Difference columns**: three ankle descriptions "
      "swap minimum and maximum.")
    w("")
    w("## 4. Demographics by group")
    w("")
    d = demo[["group", "n", "age_mean", "age_sd", "age_ci95_low", "age_ci95_high", "bmi_mean", "female_pct"]].copy()
    for c in ["age_mean", "age_sd", "age_ci95_low", "age_ci95_high", "bmi_mean", "female_pct"]:
        d[c] = d[c].map(lambda x: _f(x, 1))
    d.columns = ["group", "n", "age mean", "age SD", "age 95% CI low", "age 95% CI high", "BMI mean", "% female"]
    w(_table(d))
    t = s["demographic_tests"]
    w("")
    w(f"Controls average {dm['healthy control']['age_mean']} years against {dm['knee OA']['age_mean']} (knee OA) and "
      f"{dm['lumbar stenosis']['age_mean']} (lumbar stenosis). Age differs across groups (Kruskal Wallis "
      f"p {_p(t['age_kruskal_p'])}), as does BMI (p {_p(t['bmi_kruskal_p'])}); sex does not "
      f"(chi square p {_p(t['sex_chi2_p'])}). **Controls are not age matched.** Patients were candidates for "
      "surgery (advanced disease) or, for cervical stenosis, partly treated conservatively, so results do not "
      "describe early disease. Kinematic summaries per group with 95% CIs, medians and IQRs: "
      "`tables/t05_features_by_group.csv`.")
    w("")
    w("## 5. Age and sex adjusted group contrasts")
    w("")
    w("Pre-specified features (fixed before fitting, KneeMinimum excluded for its scale): "
      + ", ".join(f"`{x}`" for x in ctr["features_prespecified"]) + ". Model per feature: OLS, feature on group "
      "(reference healthy control) plus age and sex, HC3 robust standard errors, Holm correction across the "
      f"{ctr['n_contrasts_per_model']} group by feature contrasts. Speed is not used as a covariate because it lies "
      "on the pathway between disease and joint angles.")
    w("")
    m = adj.merge(unadj[["feature", "group", "difference_vs_control", "p_holm"]], on=["feature", "group"],
                  suffixes=("", "_u"))
    tb = pd.DataFrame({
        "feature": m["feature"], "group": m["group"].map(D.GROUP_SHORT),
        "unadjusted diff": m["difference_vs_control_u"].map(lambda x: _f(x)),
        "adjusted diff": m["difference_vs_control"].map(lambda x: _f(x)),
        "adjusted 95% CI": [f"{_f(lo)} to {_f(hi)}" for lo, hi in zip(m["ci95_low"], m["ci95_high"])],
        "std diff": m["standardised_difference"].map(lambda x: _f(x)),
        "Holm p adjusted": m["p_holm"].map(_p),
        "Holm p unadjusted": m["p_holm_u"].map(_p),
    })
    w(_table(tb))
    w("")
    w(f"Holm significant contrasts: {ctr['significant_holm_unadjusted']} unadjusted, "
      f"{ctr['significant_holm_age_sex_adjusted']} after age and sex adjustment, "
      f"{ctr['significant_holm_age_sex_bmi_adjusted']} when BMI is added, and "
      f"{ctr['significant_holm_adjusted_flagged_removed']} after removing the {s['n_participants'] - ctr['rows_after_removing_flagged']} "
      "rows with imputation footprints.")
    def _pretty(items):
        return ", ".join(f"{a} ({b})" for a, b in (x.split("|") for x in items)) or "none"

    lost = ctr["lost_after_age_sex_adjustment"]
    w(f"Lost after age and sex adjustment: {_pretty(lost)}. "
      f"Gained: {_pretty(ctr['gained_after_age_sex_adjustment'])}. "
      f"Lost after removing flagged rows: {_pretty(ctr['lost_after_removing_flagged_rows'])}.")
    w("")
    w("Reading guide: angles are sagittal plane degrees as deposited (flexion positive). Std diff is the "
      "adjusted difference divided by the control SD. Units: Speed m/s, StancePct % of gait cycle (assumed). "
      "Caution for hip features: the deposit reports the \"affected\" side; per the paper, in controls and stenosis "
      "groups that side was chosen as the side with less hip flexion, while in hip and knee OA it is the clinical "
      "side. Hip contrasts therefore partly reflect a selection rule, not only disease. Age slopes per 10 years: "
      "`tables/t07_age_effect_per_10_years.csv`. Forest plot: `figures/fig04_adjusted_contrasts.png`.")
    w("")
    w("## 6. Imputation footprints and leakage")
    w("")
    w("The deposit states that gaps were filled with the control group mean (controls) and by nearest neighbours "
      "(patients), but imputed cells are not flagged and the file has no missing values left, so **the original "
      "missingness cannot be recovered**. This project detects footprints instead: a value stored with about 15 "
      "decimals that appears in two or more rows cannot be an independent measurement, and an exact 0.0 side "
      "difference means both sides are identical. This is a lower bound: a cell imputed only once in its column "
      "leaves no trace.")
    w("")
    fl = flags.copy(); fl["pct_rows_flagged"] = fl["pct_rows_flagged"].map(lambda x: _f(x, 1))
    fl.columns = ["group", "n", "rows flagged", "% rows flagged", "suspected cells"]
